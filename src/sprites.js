function seg(ctx, x0, y0, x1, y1, w) {
  const steps = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0), 0.1) * 2;
  const o = (w - 1) / 2;
  for (let i = 0; i <= steps; i++) {
    const t = i / steps;
    ctx.fillRect(Math.round(x0 + (x1 - x0) * t - o), Math.round(y0 + (y1 - y0) * t - o), w, w);
  }
}
function limb(ctx, a, b, c, w) { seg(ctx, a[0], a[1], b[0], b[1], w); seg(ctx, b[0], b[1], c[0], c[1], w); }

function drawFrame(ctx, F, g, col) {
  ctx.fillStyle = col;
  ctx.globalAlpha = 0.22; ctx.fillRect(0, GH - 1, GW, 1); ctx.globalAlpha = 1; // земля
  if (F.bar) { ctx.globalAlpha = 0.4; ctx.fillRect(2, 1, 12, 1); ctx.globalAlpha = 1; }
  const fem = g === 'f', side = F.v === 's';
  const shL = side ? F.s : [F.s[0] - 2, F.s[1]];
  const shR = side ? F.s : [F.s[0] + 2, F.s[1]];
  const hpL = side ? F.p : [F.p[0] - 1, F.p[1]];
  const hpR = side ? F.p : [F.p[0] + 1, F.p[1]];
  // дальние конечности (вид сбоку) — бледнее
  if (side) {
    if (F.kR && F.fR) { ctx.globalAlpha = 0.4; limb(ctx, hpR, F.kR, F.fR, 2); ctx.globalAlpha = 1; }
    if (F.eR && F.hR) { ctx.globalAlpha = 0.4; limb(ctx, shR, F.eR, F.hR, 2); ctx.globalAlpha = 1; }
    limb(ctx, hpL, F.kL, F.fL, 2);
  } else {
    limb(ctx, hpL, F.kL, F.fL, 2);
    if (F.kR && F.fR) limb(ctx, hpR, F.kR, F.fR, 2);
  }
  // туловище
  seg(ctx, F.s[0], F.s[1], F.p[0], F.p[1], fem ? 2 : 3);
  if (fem) ctx.fillRect(Math.round(F.p[0]) - 2, Math.round(F.p[1]), 5, 2);       // бёдра шире
  else ctx.fillRect(Math.round(F.s[0]) - 2, Math.round(F.s[1]), 5, 2);            // плечи шире
  // руки
  limb(ctx, shL, F.eL, F.hL, 2);
  if (!side && F.eR && F.hR) limb(ctx, shR, F.eR, F.hR, 2);
  // голова
  const hx = Math.round(F.h[0]), hy = Math.round(F.h[1]);
  ctx.fillRect(hx - 1, hy - 1, 3, 3);
  if (fem) { // хвостик
    if (side) { ctx.fillRect(hx - 2, hy - 1, 1, 1); ctx.fillRect(hx - 3, hy, 1, 2); }
    else { ctx.fillRect(hx - 2, hy, 1, 2); ctx.fillRect(hx + 2, hy, 1, 2); }
  }
  // гири
  if (F.kb) for (const [bx, by, dir] of F.kb) {
    const x = Math.round(bx), y = Math.round(by);
    if (dir === 'up') ctx.fillRect(x - 1, Math.max(0, y - 2), 2, 2);
    else ctx.fillRect(x - 1, y + 1, 2, 2);
  }
}

